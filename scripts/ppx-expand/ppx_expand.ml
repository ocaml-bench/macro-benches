(* Replace ppx preprocessing with the expanded source. Built and run by
   scripts/ppx-expand.sh on the pinned switch, from the repo root, after it
   has built every benchmark into DIR: every ppx output in that build is
   expanded, except for the ppxs' own code.

     ppx_expand --build-dir DIR [--ppx-src-only]

   Writes the list of files it wrote, with their hashes, to the marker; the
   script checks that against scripts/ppx-expand/manifest. *)

open Parsetree

(* Inside duniverse/ so it travels with a cached duniverse/ and vendor/. *)
let marker = "duniverse/.ppx-expanded"

(* Lowest OCaml release the tree supports; the version buckets start here. *)
let min_ocaml = (5, 4, 0)

let header = "(* Generated by scripts/ppx-expand from the ppx-preprocessed source. Do not edit. *)\n"
let ppx_kinds = [ "pps"; "staged_pps" ]

let die fmt = Printf.ksprintf (fun s -> prerr_endline ("ppx-expand: " ^ s); exit 1) fmt
let read_file path = In_channel.with_open_bin path In_channel.input_all
let write_file path text = Out_channel.with_open_bin path (fun oc -> output_string oc text)
let starts_with ~prefix s = String.starts_with ~prefix s
let ends_with ~suffix s = String.ends_with ~suffix s
let contains_sub sub s = try ignore (Str.search_forward (Str.regexp_string sub) s 0); true with Not_found -> false
let abspath p = if Filename.is_relative p then Filename.concat (Sys.getcwd ()) p else p

let rec rm_rf path =
  if Sys.is_directory path then begin
    Array.iter (fun f -> rm_rf (Filename.concat path f)) (Sys.readdir path);
    Sys.rmdir path
  end
  else Sys.remove path

(* Run argv (in cwd, with extra environment), returning exit code, stdout and
   stderr. Goes through /bin/sh for the redirections. *)
let run ?(cwd = ".") ?(env = []) argv =
  let out = Filename.temp_file "ppx-expand" ".out" and err = Filename.temp_file "ppx-expand" ".err" in
  let envs = List.map (fun (k, v) -> Filename.quote (k ^ "=" ^ v)) env in
  let cmd =
    Printf.sprintf "cd %s && %s%s > %s 2> %s" (Filename.quote cwd)
      (if envs = [] then "" else "env " ^ String.concat " " envs ^ " ")
      (Filename.quote_command (List.hd argv) (List.tl argv))
      (Filename.quote out) (Filename.quote err)
  in
  let code = Sys.command cmd in
  let o = read_file out and e = read_file err in
  Sys.remove out;
  Sys.remove err;
  (code, o, e)

let run_ok ?cwd ?env argv =
  let code, out, err = run ?cwd ?env argv in
  if code <> 0 then begin
    prerr_string err;
    die "%s failed" (String.concat " " (List.filteri (fun i _ -> i < 4) argv))
  end;
  out

(* ------------------------------------------------------------- s-expressions *)

type sexp = Atom of string | List of sexp list

let sexp_parse text =
  let n = String.length text in
  let pos = ref 0 in
  let rec items acc =
    while !pos < n && (match text.[!pos] with ' ' | '\n' | '\t' | '\r' -> true | _ -> false) do incr pos done;
    if !pos >= n then List.rev acc
    else
      match text.[!pos] with
      | ')' -> incr pos; List.rev acc
      | '(' -> incr pos; let l = items [] in items (List l :: acc)
      | '"' ->
          incr pos;
          let b = Buffer.create 16 in
          while text.[!pos] <> '"' do
            if text.[!pos] = '\\' then begin
              Buffer.add_char b (match text.[!pos + 1] with 'n' -> '\n' | 't' -> '\t' | c -> c);
              pos := !pos + 2
            end
            else (Buffer.add_char b text.[!pos]; incr pos)
          done;
          incr pos;
          items (Atom (Buffer.contents b) :: acc)
      | _ ->
          let start = !pos in
          while !pos < n && not (String.contains " \n\t\r()\"" text.[!pos]) do incr pos done;
          items (Atom (String.sub text start (!pos - start)) :: acc)
  in
  items []

let field name = function
  | List items ->
      List.find_map (function List (Atom k :: v) when k = name -> Some v | _ -> None) items
  | Atom _ -> None

let field_exn name s = match field name s with Some v -> v | None -> die "describe: no field %s" name
let atom = function Atom a -> a | List _ -> die "describe: expected an atom"

(* ------------------------------------------------------------- dune file text *)

(* (start, stop) of each top-level parenthesised form in text[start, stop),
   skipping comments and strings. *)
let forms text start stop =
  let i = ref start and depth = ref 0 and fstart = ref 0 and acc = ref [] in
  while !i < stop do
    (match text.[!i] with
     | ';' -> while !i < stop && text.[!i] <> '\n' do incr i done; decr i
     | '#' when !i + 1 < stop && text.[!i + 1] = '|' ->
         i := !i + 2;
         while !i + 1 < stop && not (text.[!i] = '|' && text.[!i + 1] = '#') do incr i done;
         incr i
     | '"' ->
         incr i;
         while !i < stop && text.[!i] <> '"' do if text.[!i] = '\\' then incr i; incr i done
     | '(' -> if !depth = 0 then fstart := !i; incr depth
     | ')' ->
         decr depth;
         if !depth = 0 then acc := (!fstart, !i + 1) :: !acc
     | _ -> ());
    incr i
  done;
  List.rev !acc

let children text (a, b) = forms text (a + 1) (b - 1)

let atoms text (a, b) =
  let s = String.sub text a (b - a) in
  let r = Str.regexp "[^ \n\t\r()\"]+" in
  let rec go i acc =
    match Str.search_forward r s i with
    | j -> go (j + String.length (Str.matched_string s)) (Str.matched_string s :: acc)
    | exception Not_found -> List.rev acc
  in
  go 0 []

let head_re = Str.regexp "([ \n\t\r]*\\([^ \n\t\r()\"]+\\)"
let head text (a, _) = if Str.string_match head_re text a then Str.matched_group 1 text else ""
let child text span name = List.find_opt (fun c -> head text c = name) (children text span)

(* A dune file in OCaml syntax (infer) builds its stanzas from {|...|} literals. *)
let stanza_regions text =
  if starts_with ~prefix:"(*" (String.trim text) then begin
    let acc = ref [] and i = ref 0 in
    (try
       while true do
         let a = Str.search_forward (Str.regexp_string "{|") text !i + 2 in
         let b = Str.search_forward (Str.regexp_string "|}") text a in
         acc := (a, b) :: !acc;
         i := b + 2
       done
     with Not_found -> ());
    List.rev !acc
  end
  else [ (0, String.length text) ]

let remove_span text (a, b) =
  let a = ref a in
  while !a > 0 && String.contains " \t\n" text.[!a - 1] do decr a done;
  String.sub text 0 !a ^ String.sub text b (String.length text - b)

(* ------------------------------------------------------------- dune queries *)

type kind = Library | Executables

(* A library or executable(s) stanza, identified by its directory and names. *)
type stanza = { kind : kind; dir : string; names : string list }

let dune build_dir args = run_ok ("dune" :: args @ [ "--root"; "."; "--build-dir"; build_dir ])
let stanza_heads = [ "library"; "executable"; "executables"; "test"; "tests" ]

let rec mkdir_p d =
  if not (Sys.file_exists d) then begin
    mkdir_p (Filename.dirname d);
    Sys.mkdir d 0o755
  end

let find_stanza text st =
  let ids span fields =
    List.concat_map
      (fun f -> match child text span f with Some c -> List.tl (atoms text c) | None -> [])
      fields
  in
  List.find_map
    (fun (ra, rb) ->
      List.find_opt
        (fun span ->
          match (st.kind, head text span) with
          | Library, "library" -> List.mem (List.hd st.names) (ids span [ "name"; "public_name" ])
          | Executables, ("executable" | "executables" | "test" | "tests") ->
              let ids = ids span [ "name"; "names"; "public_name"; "public_names" ] in
              List.for_all (fun n -> List.mem n ids) st.names
          | _ -> false)
        (forms text ra rb))
    (stanza_regions text)

type preprocess =
  | All of (int * int)  (* the (preprocess ...) field *)
  | Per_module of (int * int) * ((int * int) * bool * string list) list

let module_name file = String.lowercase_ascii (List.hd (String.split_on_char '.' (Filename.basename file)))

(* The stanza's module files that go through a ppx, and its preprocess field. *)
let ppx_modules text span modules =
  match child text span "preprocess" with
  | None -> ([], None)
  | Some field -> (
      match children text field with
      | [] -> ([], None)
      | inner :: _ when List.mem (head text inner) ppx_kinds -> (modules, Some (All field))
      | inner :: _ when head text inner = "per_module" ->
          let entries =
            List.map
              (fun entry ->
                match children text entry with
                | spec :: _ ->
                    let mods = List.map String.lowercase_ascii (atoms text (snd spec, snd entry - 1)) in
                    (entry, List.mem (head text spec) ppx_kinds, mods)
                | [] -> die "unexpected per_module entry")
              (children text inner)
          in
          let chosen = List.concat_map (fun (_, p, ms) -> if p then ms else []) entries in
          (List.filter (fun f -> List.mem (module_name f) chosen) modules, Some (Per_module (field, entries)))
      | _ -> ([], None))

let ids text span fields =
  List.concat_map (fun f -> match child text span f with Some c -> List.tl (atoms text c) | None -> []) fields

let stanza_of text span dir =
  if head text span = "library" then { kind = Library; dir; names = [ List.hd (ids text span [ "name"; "public_name" ]) ] }
  else
    let names = ids text span [ "name"; "names" ] in
    { kind = Executables; dir; names = (if names = [] then ids text span [ "public_name"; "public_names" ] else names) }

(* Whether the stanza's (modules ...) field admits module m. *)
let admits text span m =
  match child text span "modules" with
  | None -> true
  | Some f ->
      let a = List.map String.lowercase_ascii (List.tl (atoms text f)) in
      if List.exists (fun x -> String.contains x '%') a then true (* filled in by an OCaml-syntax dune file *)
      else if List.mem ":standard" a then
        let rec excluded = function "\\" :: rest -> List.mem m rest | _ :: rest -> excluded rest | [] -> false in
        not (excluded a)
      else List.mem m a

(* The dune file and stanza that build the module file src. *)
let owner src =
  let m = module_name src in
  let rec up d first =
    let dune_file = Filename.concat d "dune" in
    let found =
      if not (Sys.file_exists dune_file) then None
      else
        let text = read_file dune_file in
        if not (first || contains_sub "(include_subdirs" text) then None
        else
          let cands =
            List.concat_map
              (fun (ra, rb) -> List.filter (fun sp -> List.mem (head text sp) stanza_heads && admits text sp m) (forms text ra rb))
              (stanza_regions text)
          in
          match cands with
          | [] -> None
          | [ sp ] -> Some (dune_file, stanza_of text sp d)
          | _ -> (
              match List.filter (fun sp -> fst (ppx_modules text sp [ src ]) <> []) cands with
              | [ sp ] -> Some (dune_file, stanza_of text sp d)
              | _ -> die "%s: cannot tell which stanza in %s builds it" src dune_file)
    in
    match found with
    | Some _ -> found
    | None -> if d = "." || Filename.dirname d = d then None else up (Filename.dirname d) false
  in
  up (Filename.dirname src) true

(* Rewriters, and libraries built on ppxlib: only needed to build the ppxs. *)
let is_ppx_machinery text span =
  let has field p = match child text span field with Some f -> List.exists p (List.tl (atoms text f)) | None -> false in
  has "kind" (fun a -> a = "ppx_rewriter" || a = "ppx_deriver")
  || has "libraries" (fun a -> starts_with ~prefix:"ppxlib" a)
  || has "preprocess" (fun a -> starts_with ~prefix:"ppxlib" a)

(* Rewriter names in the stanza's preprocess field (flags and driver arguments dropped). *)
let ppx_names text span =
  match child text span "preprocess" with
  | None -> []
  | Some p ->
      let rec specs sp = if List.mem (head text sp) ppx_kinds then [ sp ] else List.concat_map specs (children text sp) in
      let rec take = function [] | "--" :: _ -> [] | a :: r -> if a.[0] = '-' then take r else a :: take r in
      List.sort_uniq compare (List.concat_map (fun sp -> take (List.tl (atoms text sp))) (specs p))

(* The libraries each set of rewriters adds to a stanza implicitly (its
   ppx_runtime_libraries), read from dune by describing a probe library that
   uses them, next to the stanza so the same libraries are visible. Keys are
   (dune file, rewriters). *)
let runtime_libs bd keys =
  let stanza i set = Printf.sprintf "\n(library\n (name ppx_expand_probe_%d)\n (modules)\n (preprocess (pps %s)))\n" i (String.concat " " set) in
  let saved = Hashtbl.create 16 and made = ref [] in
  List.iteri
    (fun i (dune_file, set) ->
      let text = read_file dune_file in
      if not (Hashtbl.mem saved dune_file) then Hashtbl.add saved dune_file text;
      if stanza_regions text = [ (0, String.length text) ] then write_file dune_file (text ^ stanza i set)
      else begin
        (* An OCaml-syntax dune file: use a subdirectory. *)
        let d = Filename.concat (Filename.dirname dune_file) (Printf.sprintf "ppx-expand-probe-%d" i) in
        mkdir_p d;
        made := d :: !made;
        write_file (Filename.concat d "dune") (stanza i set)
      end)
    keys;
  let dirs = List.sort_uniq compare (List.map (fun (d, _) -> Filename.dirname d) keys @ !made) in
  let code, out, err =
    run ("dune" :: [ "describe"; "workspace"; "--lang"; "0.1"; "--profile"; "release" ] @ dirs @ [ "--root"; "."; "--build-dir"; bd ])
  in
  Hashtbl.iter write_file saved;
  List.iter rm_rf !made;
  if code <> 0 then (prerr_string err; die "dune describe of the probes failed");
  let items = match sexp_parse out with [ List l ] -> l | _ -> die "describe: bad output" in
  let libs = List.filter_map (function List [ Atom "library"; f ] -> Some f | _ -> None) items in
  let one f name = match field name f with Some [ x ] -> x | _ -> die "describe: no %s" name in
  let name_of = Hashtbl.create 512 in
  List.iter (fun f -> Hashtbl.replace name_of (atom (one f "uid")) (atom (one f "name"))) libs;
  List.mapi
    (fun i ((dune_file, set) as key) ->
      let probe = Printf.sprintf "ppx_expand_probe_%d" i in
      match List.find_opt (fun f -> atom (one f "name") = probe) libs with
      | Some f ->
          let reqs = match one f "requires" with List l -> List.map atom l | Atom _ -> [] in
          (key, List.filter_map (Hashtbl.find_opt name_of) reqs)
      | None -> die "dune cannot resolve the rewriters %s next to %s" (String.concat " " set) dune_file)
    keys

(* The file named base under dir (include_subdirs puts modules in subdirectories). *)
let find_file dir base =
  let rec go d =
    if Sys.file_exists (Filename.concat d base) then Some (Filename.concat d base)
    else
      Array.fold_left
        (fun acc f ->
          match acc with
          | Some _ -> acc
          | None -> let p = Filename.concat d f in if f.[0] <> '.' && Sys.is_directory p then go p else None)
        None (Sys.readdir d)
  in
  match go dir with Some p -> p | None -> die "%s: no file %s" dir base

(* The alternatives of the (select target ...) in the stanza's libraries. *)
let select_alternatives text span target =
  match child text span "libraries" with
  | None -> None
  | Some l ->
      List.find_map
        (fun sp ->
          if head text sp = "select" && List.nth_opt (atoms text sp) 1 = Some target then
            Some (List.filter_map (fun c -> match List.rev (atoms text c) with alt :: _ :: _ -> Some alt | _ -> None) (children text sp))
          else None)
        (children text l)

(* Remove the ppx part of the stanza's preprocess field, and preprocessor_deps
   when nothing is left to preprocess. *)
let drop_ppx text st =
  let span = Option.get (find_stanza text st) in
  match snd (ppx_modules text span []) with
  | None -> text
  | Some pre ->
      let field, rest =
        match pre with
        | All f -> (f, [])
        | Per_module (f, entries) ->
            (f, List.filter_map (fun ((a, b), p, _) -> if p then None else Some (String.sub text a (b - a))) entries)
      in
      if rest <> [] then
        String.sub text 0 (fst field)
        ^ "(preprocess\n  (per_module\n   " ^ String.concat "\n   " rest ^ "))"
        ^ String.sub text (snd field) (String.length text - snd field)
      else
        let text = remove_span text field in
        let span = Option.get (find_stanza text st) in
        match child text span "preprocessor_deps" with Some d -> remove_span text d | None -> text

let add_libraries text st libs =
  let a, b = Option.get (find_stanza text st) in
  let libs = String.concat " " libs in
  match child text (a, b) "libraries" with
  | Some (_, y) -> String.sub text 0 (y - 1) ^ " " ^ libs ^ String.sub text (y - 1) (String.length text - y + 1)
  | None -> String.sub text 0 (b - 1) ^ "\n (libraries " ^ libs ^ ")" ^ String.sub text (b - 1) (String.length text - b + 1)

(* Files a (rule ...) stanza produces. *)
let rule_targets text span =
  match child text span "targets" with
  | Some t -> List.tl (atoms text t)
  | None ->
      let rec walk span =
        (match head text span with
         | "copy" -> [ List.nth (atoms text span) 2 ]
         | "with-stdout-to" -> [ List.nth (atoms text span) 1 ]
         | _ -> [])
        @ List.concat_map walk (children text span)
      in
      walk span

(* Generated modules that a ppx rewrites become sources: remove the rules that
   produce them. Returns the dune files edited. *)
let materialise generated =
  let dirs = List.sort_uniq compare (List.map Filename.dirname generated) in
  List.map
    (fun d ->
      let dune_file = Filename.concat d "dune" in
      let names = List.filter_map (fun g -> if Filename.dirname g = d then Some (Filename.basename g) else None) generated in
      let text = read_file dune_file in
      let rules =
        List.filter
          (fun span ->
            head text span = "rule"
            &&
            let mods = List.filter (fun t -> ends_with ~suffix:".ml" t || ends_with ~suffix:".mli" t) (rule_targets text span) in
            if List.exists (fun m -> List.mem m names) mods then begin
              List.iter (fun m -> if not (List.mem m names) then die "%s: a rule also makes %s, which stays generated" dune_file m) mods;
              true
            end
            else false)
          (forms text 0 (String.length text))
      in
      let covered = List.concat_map (rule_targets text) rules in
      List.iter (fun n -> if not (List.mem n covered) then die "%s: no rule found for %s" dune_file n) names;
      write_file dune_file (List.fold_left remove_span text (List.rev rules));
      dune_file)
    dirs

(* ------------------------------------------------------------- ASTs *)

type ast = Str of structure | Sig of signature

let is_intf path = Filename.check_suffix path ".mli"

(* Not Pparse.read_ast, which deletes the file it reads. *)
let read_pp path =
  In_channel.with_open_bin path (fun ic ->
      let magic = if is_intf path then Config.ast_intf_magic_number else Config.ast_impl_magic_number in
      if really_input_string ic (String.length magic) <> magic then die "%s: not a binary AST for this compiler" path;
      ignore (input_value ic : string);
      if is_intf path then Sig (input_value ic : signature) else Str (input_value ic : structure))

let parse_source ~intf path text =
  let lexbuf = Lexing.from_string text in
  Location.init lexbuf path;
  if intf then Sig (Parse.interface lexbuf) else Str (Parse.implementation lexbuf)

(* The driver records its context (compiler version, cookies) as a leading
   attribute; it is not part of the program. *)
let context_attr = "ocaml.ppx.context"

let split_header = function
  | Str ({ pstr_desc = Pstr_attribute { attr_name = { txt; _ }; attr_payload; _ }; _ } :: rest) when txt = context_attr ->
      (Some attr_payload, Str rest)
  | Sig ({ psig_desc = Psig_attribute { attr_name = { txt; _ }; attr_payload; _ }; _ } :: rest) when txt = context_attr ->
      (Some attr_payload, Sig rest)
  | ast -> (None, ast)

(* Rewrites for ASTs that ppxs build but that have no source syntax. Each keeps
   the meaning of the program. *)
let underscore = "_ppx_expand_underscore"

let normalise =
  let open Ast_mapper in
  let pat m p =
    match p.ppat_desc with
    (* ppx_deriving_yojson binds and reads a value named "_" *)
    | Ppat_var ({ txt = "_"; _ } as v) -> { p with ppat_desc = Ppat_var { v with txt = underscore } }
    | _ -> default_mapper.pat m p
  in
  let expr m e =
    match e.pexp_desc with
    | Pexp_ident ({ txt = Longident.Lident "_"; _ } as v) ->
        { e with pexp_desc = Pexp_ident { v with txt = Longident.Lident underscore } }
    (* ppx_deriving's ord on a type with no constructors: a function with no cases *)
    | Pexp_function ([], None, Pfunction_cases ([], loc, _)) ->
        let open Ast_helper in
        let param = { pparam_loc = loc; pparam_desc = Pparam_val (Nolabel, None, Pat.any ~loc ()) } in
        let false_ = Exp.construct ~loc { txt = Longident.Lident "false"; loc } None in
        Exp.function_ ~loc ~attrs:e.pexp_attributes [ param ] None (Pfunction_body (Exp.assert_ ~loc false_))
    (* Attributes on the declaration of a local open have no syntax; the
       nearest place that covers them is the let-open expression itself. *)
    | Pexp_open (({ popen_attributes = _ :: _ as attrs; _ } as od), body) ->
        default_mapper.expr m
          { e with
            pexp_desc = Pexp_open ({ od with popen_attributes = [] }, body);
            pexp_attributes = e.pexp_attributes @ attrs }
    | _ -> default_mapper.expr m e
  in
  (* [let (x : 'a. t) = e] only parses as [let x : 'a. t = e] *)
  let value_binding m vb =
    match default_mapper.value_binding m vb with
    | { pvb_pat =
          { ppat_desc = Ppat_constraint (({ ppat_desc = Ppat_var _; _ } as p), ({ ptyp_desc = Ptyp_poly _; _ } as typ));
            ppat_attributes = [];
            _ };
        pvb_constraint = None;
        _ } as vb ->
        { vb with pvb_pat = p; pvb_constraint = Some (Pvc_constraint { locally_abstract_univars = []; typ }) }
    | vb -> vb
  in
  { default_mapper with pat; expr; value_binding }

let erase_locations =
  let open Ast_mapper in
  { default_mapper with
    location = (fun _ _ -> Location.none);
    pat = (fun m p -> { (default_mapper.pat m p) with ppat_loc_stack = [] });
    expr = (fun m e -> { (default_mapper.expr m e) with pexp_loc_stack = [] });
    typ = (fun m t -> { (default_mapper.typ m t) with ptyp_loc_stack = [] }) }

let map (m : Ast_mapper.mapper) = function Str s -> Str (m.structure m s) | Sig s -> Sig (m.signature m s)
let equal a b = map erase_locations a = map erase_locations b

let print ast =
  let buf = Buffer.create 65536 in
  let ppf = Format.formatter_of_buffer buf in
  Format.pp_set_margin ppf 80;
  (match ast with Str s -> Pprintast.structure ppf s | Sig s -> Pprintast.signature ppf s);
  Format.pp_print_newline ppf ();
  Buffer.contents buf

(* The driver output pp as source, or None when it parses to the same AST as
   the file reference (the ppx did nothing). Fails unless the printed source
   parses back to the same AST. *)
let expand ?reference pp =
  let intf = is_intf pp in
  let _, ast = split_header (read_pp pp) in
  let unchanged =
    match reference with
    | Some r -> ( try equal ast (parse_source ~intf r (read_file r)) with _ -> false)
    | None -> false
  in
  if unchanged then None
  else
    let ast = map normalise ast in
    let text = print ast in
    let back =
      try parse_source ~intf pp text
      with exn ->
        Location.report_exception Format.err_formatter exn;
        die "%s: printed source does not parse" pp
    in
    if not (equal ast back) then die "%s: printed source does not parse back to the same AST" pp;
    Some text

(* The value of cookie name in the driver output's header, as source. *)
let cookie pp name =
  let rec find e =
    match e.pexp_desc with
    | Pexp_construct ({ txt = Lident "::"; _ }, Some { pexp_desc = Pexp_tuple [ (_, x); (_, rest) ]; _ }) -> (
        match x.pexp_desc with
        | Pexp_tuple [ (_, { pexp_desc = Pexp_constant { pconst_desc = Pconst_string (n, _, _); _ }; _ }); (_, v) ]
          when n = name -> Some v
        | _ -> find rest)
    | _ -> None
  in
  match fst (split_header (read_pp pp)) with
  | Some (PStr [ { pstr_desc = Pstr_eval ({ pexp_desc = Pexp_record (fields, None); _ }, _); _ } ]) ->
      List.find_map (fun ({ Location.txt; _ }, e) -> if Longident.last txt = "cookies" then find e else None) fields
      |> Option.map (Format.asprintf "%a" Pprintast.expression)
  | _ -> None

(* ------------------------------------------------------------- version buckets *)

let conditional = Str.regexp {|\[\(%%\|@@@\|@@\|@\)\(if\|elif\|ifdef\|ifndef\|import\)\b|}

let version_test =
  Str.regexp {|ocaml_version *\(<\|>\|<=\|>=\|=\|<>\) *( *\([0-9]+\) *, *\([0-9]+\) *\(, *\([0-9]+\) *\)?)|}

let contains re s = try ignore (Str.search_forward re s 0); true with Not_found -> false

(* Representative versions of the ranges the file's version tests split the
   supported releases into. *)
let buckets text =
  if contains (Str.regexp {|\bflambda2?\b|}) text then die "flambda conditionals are not supported by the version buckets";
  let rec go i acc =
    match Str.search_forward version_test text i with
    | j ->
        let g n = try int_of_string (Str.matched_group n text) with Not_found -> 0 in
        let v = (g 2, g 3, g 5) in
        go (j + 1) (if v > min_ocaml then v :: acc else acc)
    | exception Not_found -> acc
  in
  List.sort_uniq compare (min_ocaml :: go 0 [])

(* OxCaml's %{ocaml_version}. A file with conditionals on oxcaml or
   flambda_backend also gets an expansion for it. *)
let oxcaml_version = "5.4.0+ox"
let oxcaml_test = Str.regexp {|\boxcaml\b\|\bflambda_backend\b|}

let pp_target src = Filename.remove_extension src ^ ".pp" ^ Filename.extension src
let version_string (a, b, c) = Printf.sprintf "%d.%d.%d" a b c
let version_name (a, b, c) = Printf.sprintf "v%d_%d_%d" a b c

(* The ppx driver invocation dune uses for target, relative to the build context. *)
let driver_command build_dir target =
  let rec runs = function
    | List (Atom "run" :: (Atom exe :: _ as argv)) when ends_with ~suffix:"ppx.exe" exe -> [ List.map atom argv ]
    | List l -> List.concat_map runs l
    | Atom _ -> []
  in
  match List.concat_map runs (sexp_parse (dune build_dir [ "rules"; "--profile"; "release"; target ])) with
  | [ argv ] -> argv
  | _ -> die "cannot find the ppx driver invocation for %s" target

let with_output argv out = List.mapi (fun i a -> if i > 0 && List.nth argv (i - 1) = "-o" then out else a) argv

(* ppx_optcomp's initial environment as a cookie value, or None when the driver
   has no ppx_optcomp: read from the driver's output for an empty file. *)
let optcomp_init_env ctx argv tmp =
  let empty = Filename.concat tmp "empty.ml" and out = Filename.concat tmp "empty.pp.ml" in
  write_file empty "";
  let argv =
    List.mapi
      (fun i a ->
        if a = "--intf" then "--impl"
        else if i > 0 && (List.nth argv (i - 1) = "--impl" || List.nth argv (i - 1) = "--intf") then empty
        else a)
      (with_output argv out)
  in
  ignore (run_ok ~cwd:ctx argv);
  cookie out "ppx_optcomp.env"

(* Re-run the driver as if the compiler were version v (OxCaml if ox). *)
let expand_as ?(ox = false) ctx argv init_env v out =
  let argv = with_output argv out in
  let argv =
    match init_env with
    | None -> argv
    | Some env ->
        let (a, b, c) = v in
        let env =
          Str.global_replace (Str.regexp {|~ocaml_version:(Defined ([^)]*))|})
            (Printf.sprintf "~ocaml_version:(Defined (%d, %d, %d))" a b c) env
        in
        let env =
          if not ox then env
          else
            List.fold_left
              (fun env flag ->
                Str.global_replace (Str.regexp_string ("~" ^ flag ^ ":(Defined false)")) ("~" ^ flag ^ ":(Defined true)") env)
              env [ "flambda_backend"; "flambda2" ]
        in
        List.hd argv :: "--cookie" :: ("ppx_optcomp.env=" ^ env) :: List.tl argv
  in
  let version = if ox then oxcaml_version else version_string v in
  ignore (run_ok ~cwd:ctx ~env:[ ("PPX_EXPAND_OCAML_VERSION", version) ] argv)

(* dune rules picking src's expansion: (version range, file) pairs, plus an
   OxCaml file, which the ranges then exclude. *)
let variant_rules src ranges ox_file =
  let base = Filename.basename src in
  let ox = "%{ocaml_version} " ^ oxcaml_version in
  let rule conds v =
    let cond = match conds with [ c ] -> c | cs -> "(and " ^ String.concat " " cs ^ ")" in
    Printf.sprintf "\n(rule\n (targets %s)\n (deps %s)\n (enabled_if %s)\n (action (copy %s %s)))\n" base v cond v base
  in
  String.concat ""
    (List.map
       (fun (lo, hi, v) ->
         let conds =
           Option.to_list (Option.map (fun lo -> "(>= %{ocaml_version} " ^ version_string lo ^ ")") lo)
           @ Option.to_list (Option.map (fun hi -> "(< %{ocaml_version} " ^ version_string hi ^ ")") hi)
           @ if ox_file = None then [] else [ "(<> " ^ ox ^ ")" ]
         in
         rule (if conds = [] then [ "true" ] else conds) v)
       ranges
    @ match ox_file with Some f -> [ rule [ "(= " ^ ox ^ ")" ] f ] | None -> [])

(* ------------------------------------------------------------- manifest *)

let deleted_hash = String.make 64 '-'
let hash path = Digest.BLAKE256.to_hex (Digest.BLAKE256.file path)

(* "hash  path" for every file written; ppx-expand.sh compares this with the
   committed manifest. *)
let manifest_text written deleted =
  let paths = List.sort_uniq compare (written @ deleted) in
  "# BLAKE2b-256 of every file scripts/ppx-expand.sh wrote (dashes: deleted).\n"
  ^ String.concat ""
      (List.map (fun p -> (if List.mem p deleted then deleted_hash else hash p) ^ "  " ^ p ^ "\n") paths)

(* ------------------------------------------------------------- main *)

let is_binary_ast path =
  In_channel.with_open_bin path (fun ic ->
      match really_input_string ic 9 with s -> s = "Caml1999M" || s = "Caml1999N" | exception End_of_file -> false)

let () =
  let build_dir = ref "" and ppx_src_only = ref false in
  Arg.parse
    [ ("--build-dir", Arg.Set_string build_dir, "DIR build of every benchmark, on this switch");
      ("--ppx-src-only", Arg.Set ppx_src_only, " only expand the in-repo ppx-src/ sources (before the build)") ]
    (fun a -> die "unexpected argument %s" a)
    "ppx_expand --build-dir DIR [--ppx-src-only]";
  let bd = !build_dir in
  if bd = "" then die "--build-dir is required";
  if Sys.file_exists marker then die "%s exists: the tree is already expanded" marker
  else begin
    let ctx = Filename.concat bd "default" in

    (* In-repo sources that use a ppx live in a ppx-src/ directory; their
       expansion is committed one level up. Nothing builds them, so build
       their driver outputs here. *)
    let ppx_src_dirs =
      List.filter_map
        (fun b -> let d = Filename.concat (Filename.concat "benchmarks" b) "ppx-src" in if Sys.file_exists d then Some d else None)
        (Array.to_list (Sys.readdir "benchmarks"))
    in
    let ppx_src_files =
      List.concat_map
        (fun d -> List.filter_map (fun f -> if ends_with ~suffix:".ml" f || ends_with ~suffix:".mli" f then Some (Filename.concat d f) else None)
                    (Array.to_list (Sys.readdir d)))
        ppx_src_dirs
    in
    if ppx_src_files <> [] then ignore (dune bd ([ "build"; "--profile"; "release" ] @ List.map pp_target ppx_src_files));
    let in_repo src = not (starts_with ~prefix:"duniverse/" src || starts_with ~prefix:"vendor/" src) in
    let committed_path src = Filename.concat (Filename.dirname (Filename.dirname src)) (Filename.basename src) in
    let ppx_src_writes =
      List.filter_map
        (fun src ->
          let dest = committed_path src in
          match expand (Filename.concat ctx (pp_target src)) with
          | Some e -> Some (dest, header ^ e)
          | None -> None)
        ppx_src_files
    in
    List.iter (fun (p, t) -> write_file p t) ppx_src_writes;
    if !ppx_src_only then exit 0;
    if not (Sys.file_exists ctx) then die "no build in %s" bd;

    let rec scan rel acc =
      Array.fold_left
        (fun acc f ->
          let r = if rel = "" then f else Filename.concat rel f in
          let p = Filename.concat ctx r in
          if f.[0] = '.' || (rel = "" && f = "install") then acc
          else if Sys.is_directory p then scan r acc
          else
            match (Filename.chop_suffix_opt ~suffix:".pp.ml" r, Filename.chop_suffix_opt ~suffix:".pp.mli" r) with
            | Some b, _ when is_binary_ast p -> (b ^ ".ml") :: acc
            | _, Some b when is_binary_ast p -> (b ^ ".mli") :: acc
            | _ -> acc)
        acc
        (Sys.readdir (if rel = "" then ctx else Filename.concat ctx rel))
    in
    let outputs = List.filter (fun f -> not (List.mem f ppx_src_files)) (List.sort_uniq compare (scan "" [])) in

    (* Each output's stanza; the ppxs' own code is left alone. *)
    let owned =
      List.filter_map
        (fun src ->
          match owner src with
          | None -> die "%s: no stanza builds it" src
          | Some (dune_file, st) ->
              let text = read_file dune_file in
              let span = Option.get (find_stanza text st) in
              if is_ppx_machinery text span then None
              else if in_repo src && Filename.basename st.dir <> "ppx-src" then
                die "%s uses a ppx: move it to a ppx-src/ directory (see scripts/ppx-expand.sh)" src
              else Some (src, dune_file, st))
        outputs
    in
    let stanzas =
      List.sort_uniq compare (List.filter_map (fun (_, d, st) -> if Filename.basename st.dir = "ppx-src" then None else Some (d, st)) owned)
    in
    Printf.printf "ppx-expand: %d stanzas, %d preprocessed files\n%!" (List.length stanzas) (List.length owned);
    let tmp = Filename.temp_dir "ppx-expand" "" in

    (* Expand the driver's output for target as if its source were alt. *)
    let expand_alternative target alt =
      let argv = driver_command bd (pp_target target) in
      let mirror = Filename.concat tmp "mirror" in
      if Sys.file_exists mirror then rm_rf mirror;
      mkdir_p (Filename.concat mirror (Filename.dirname target));
      write_file (Filename.concat mirror target) (read_file alt);
      let out = Filename.concat (abspath tmp) ("alt.pp" ^ Filename.extension target) in
      let argv = with_output argv out in
      ignore (run_ok ~cwd:mirror (abspath (Filename.concat ctx (List.hd argv)) :: List.tl argv));
      expand ~reference:alt out
    in

    (* Compute everything before touching the tree: dune is queried for driver
       commands below, and must still see the original sources. Each plan entry
       is (files to write, file replaced by per-version rules, generated module
       to materialise). *)
    let plan =
      List.map
        (fun (src, dune_file, st) ->
          let pp = Filename.concat ctx (pp_target src) in
          let in_tree = Sys.file_exists src in
          let dest = if in_repo src then committed_path src else src in
          let text = read_file dune_file in
          let span = Option.get (find_stanza text st) in
          match select_alternatives text span (Filename.basename src) with
          | Some alts when not in_tree ->
              let writes =
                List.filter_map
                  (fun alt ->
                    let alt = find_file st.dir alt in
                    Option.map (fun e -> (alt, header ^ e)) (expand_alternative src alt))
                  alts
              in
              (writes, None, None)
          | _ -> (
              let reference = if in_tree then src else Filename.concat ctx src in
              match expand ~reference pp with
              | None -> ([], None, None)
              | Some e when not in_tree -> ([ (src, header ^ e) ], None, Some src)
              | Some e
                when (not (contains conditional (read_file src)))
                     || (buckets (read_file src) = [ min_ocaml ] && not (contains oxcaml_test (read_file src))) ->
                  ([ (dest, header ^ e) ], None, None)
              | Some _ ->
                  let reps = buckets (read_file src) in
                  let argv = driver_command bd (pp_target src) in
                  let init_env = optcomp_init_env ctx argv tmp in
                  let vpp = Filename.concat (abspath tmp) ("v.pp" ^ Filename.extension src) in
                  let exps = List.map (fun v -> expand_as ctx argv init_env v vpp; (v, Option.get (expand vpp))) reps in
                  (* Neighbouring versions with the same expansion share a file. *)
                  let groups =
                    List.rev
                      (List.fold_left
                         (fun acc (v, e) -> match acc with (_, e') :: _ when e' = e -> acc | _ -> (v, e) :: acc)
                         [] exps)
                  in
                  (* OxCaml's expansion, unless it is the same as 5.4's. *)
                  let ox =
                    if not (contains oxcaml_test (read_file src)) then None
                    else begin
                      expand_as ~ox:true ctx argv init_env min_ocaml vpp;
                      let e = Option.get (expand vpp) in
                      if e = snd (List.hd groups) then None else Some e
                    end
                  in
                  if List.length groups = 1 && ox = None then ([ (dest, header ^ snd (List.hd groups)) ], None, None)
                  else begin
                    if in_repo src then die "%s: per-version expansions are not supported for in-repo sources" src;
                    let stem = Filename.remove_extension src and ext = Filename.extension src in
                    let ox_file = Printf.sprintf "%s.oxcaml%s" stem ext in
                    let vfile v = Printf.sprintf "%s.%s%s" stem (version_name v) ext in
                    let rec ranges = function
                      | (lo, _) :: ((hi, _) :: _ as rest) -> (lo, Some hi) :: ranges rest
                      | [ (lo, _) ] -> [ (lo, None) ]
                      | [] -> []
                    in
                    let ranges =
                      List.mapi (fun i (lo, hi) -> ((if i = 0 then None else Some lo), hi, Filename.basename (vfile lo))) (ranges groups)
                    in
                    let ox_writes = match ox with Some e -> [ (ox_file, header ^ e) ] | None -> [] in
                    ( List.map (fun (v, e) -> (vfile v, header ^ e)) groups @ ox_writes,
                      Some (src, variant_rules src ranges (Option.map (fun _ -> Filename.basename ox_file) ox)),
                      None )
                  end))
        owned
    in

    (* The rewriters' runtime libraries, which dropping the ppx would lose. *)
    let key (d, st) = let t = read_file d in (d, ppx_names t (Option.get (find_stanza t st))) in
    let runtime = runtime_libs bd (List.sort_uniq compare (List.filter (fun (_, set) -> set <> []) (List.map key stanzas))) in

    let written = ref (List.map fst ppx_src_writes) and deleted = ref [] and rules = Hashtbl.create 8 in
    let wrote p = written := p :: !written in
    List.iter
      (fun (writes, variant, _) ->
        List.iter (fun (p, text) -> write_file p text; wrote p) writes;
        Option.iter
          (fun (src, r) ->
            Sys.remove src;
            deleted := src :: !deleted;
            let d = Filename.concat (Filename.dirname src) "dune" in
            Hashtbl.replace rules d (Option.value (Hashtbl.find_opt rules d) ~default:"" ^ r))
          variant)
      plan;
    List.iter
      (fun (d, st) ->
        let text = read_file d in
        let span = Option.get (find_stanza text st) in
        let libs = Option.value (List.assoc_opt (d, ppx_names text span) runtime) ~default:[] in
        let have = ids text span [ "libraries" ] @ st.names in
        let text = drop_ppx text st in
        let text = match List.filter (fun l -> not (List.mem l have)) libs with [] -> text | l -> add_libraries text st l in
        write_file d text;
        wrote d)
      stanzas;
    Hashtbl.iter (fun d r -> write_file d (read_file d ^ r); wrote d) rules;
    (match List.filter_map (fun (_, _, g) -> g) plan with [] -> () | gs -> List.iter wrote (materialise gs));

    (* dune must still accept every edited file. *)
    ignore (dune bd ([ "describe"; "workspace"; "--lang"; "0.1"; "--profile"; "release" ]
                     @ List.sort_uniq compare (List.map (fun p -> Filename.dirname p) !written)));
    rm_rf tmp;
    let text = manifest_text !written !deleted in
    write_file marker text;
    Printf.printf "ppx-expand: expanded %d files (%d split per OCaml version)\n" (List.length (List.sort_uniq compare !written))
      (List.length !deleted)
  end
